// Carve floor rectangles out of a solid block; walls on the lower/upper face rows get
// occasional glyph bands (vault).
function carve(w, h, rects, glyphs = false) {
  const g = Array.from({ length: h }, () => Array(w).fill('#'));
  for (const [x0, y0, x1, y1, ch = '.'] of rects) for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) g[y][x] = ch;
  if (glyphs) for (let y = 1; y < h; y++) for (let x = 0; x < w; x++) {
    if (g[y][x] !== '#') continue;
    const below = g[y + 1] && g[y + 1][x];
    const below2 = g[y + 2] && g[y + 2][x];
    const face = (below && below !== '#' && below !== 'G') || (below === '#' && below2 && below2 !== '#' && below2 !== 'G');
    if (face && hash(x >> 1, y, 77) < 0.35) g[y][x] = 'G';
  }
  return g.map((r) => r.join(''));
}

